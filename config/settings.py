"""
全局配置模块

本模块定义量化因子库的全局常量和默认参数。
所有时间戳统一使用 UTC，所有数值计算遵循此配置。
"""

from __future__ import annotations

from pathlib import Path
from typing import Final

# ============================================================================
# 时区与时间相关
# ============================================================================
TIMEZONE: Final[str] = "UTC"
"""全局时区：所有时间戳统一使用 UTC"""

# ============================================================================
# 数据类型定义
# ============================================================================
ID_TYPE: Final[type] = str
"""交易对 ID 统一使用字符串类型（如 'BTCUSDT'）"""

# ============================================================================
# 交易成本默认参数
# ============================================================================
DEFAULT_FEE_RATE: Final[float] = 0.001
"""默认手续费率：0.1%（单边）"""

DEFAULT_SLIPPAGE: Final[float] = 0.0005
"""默认滑点假设：0.05%（单边）"""

# ============================================================================
# 数据相关默认值
# ============================================================================
DEFAULT_KLINE_LIMIT: Final[int] = 1000
"""单次获取 K 线数据的默认条数上限"""

DEFAULT_TIMEOUT: Final[int] = 30
"""HTTP 请求默认超时时间（秒）"""

# ============================================================================
# 数据存储路径
DEFAULT_DATA_DIR: Final[Path] = Path(__file__).resolve().parent.parent / "data"
"""数据存储根目录（medallion 三层：bronze/silver/gold），绝对路径避免 CWD 依赖"""

# ============================================================================
# 日志配置
# ============================================================================
LOG_LEVEL: Final[str] = "INFO"
"""全局日志级别"""

LOG_FORMAT: Final[str] = "%(asctime)s | %(levelname)-8s | %(name)s | %(message)s"
"""日志输出格式"""
